from tkinter import * 


def create_interface():
    interface = Tk()
    interface.title("Hospital Manager")
    interface.geometry("1000x650")
    main_frame = Frame(interface)
    title = Label(main_frame, text="Hospital Manager", font=("Arial", 24, "bold"))
    title.pack(anchor="w", padx=20, pady=20)
    patients_card = Frame(main_frame, bg="white", height=100, width=200)
    patients_card.pack_propagate(False)
    label_patients_card = Label(patients_card, text="Total Patients", font=("Arial", 12, "bold"), fg="#163B65", bg="white")
    label_patients_card.pack(pady=10)
    patients_card.pack(side="left", padx=10)
    appointments_card = Frame(main_frame, bg="white", width=200, height=100)
    appointments_card.pack(side="left", padx=10)
    appointments_card.pack_propagate(False)
    label_appointments_card = Label(appointments_card, text="Upcoming Appointments", font=("Arial", 12, "bold"), fg="#163B65", bg="white")
    label_appointments_card.pack(pady=10)
    patients_count = Label(patients_card, text="128", font=("Arial", 22, "bold"), fg="#163B65", bg="white")
    patients_count.pack()
    appointments_count = Label(appointments_card, text="24", bg="white", fg="#163B65", font=("Arial", 22, "bold"))
    appointments_count.pack(pady=10)
    staff_card = Frame(main_frame, bg="white", width=200, height=100)
    staff_card.pack(side="left", padx=10)
    staff_card_label = Label(staff_card, bg="white", text="Staff Members", font=("Arial", 12, "bold"), fg="#163B65")
    staff_card_label.pack(pady=10)
    staff_count = Label(staff_card, text="56", font=("Arial", 22, "bold"), fg="#163B65", bg="white")
    staff_count.pack()
    staff_card.pack_propagate(False)
    frame = Frame(interface, bg="#163B65", width=200)
    frame.pack(side="left", fill="y")
    frame.pack_propagate(False)
    dashboard_button = Button(frame, text="Dashboard", bg="#163B65", fg="white", font=("Arial", 12, "bold"), relief="flat", activebackground="#245584", activeforeground="white")
    dashboard_button.pack()
    main_frame.pack(side="left", fill="both", expand=True)
    return interface 

